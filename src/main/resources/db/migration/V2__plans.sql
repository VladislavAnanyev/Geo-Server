CREATE TABLE IF NOT EXISTS PLANS
(
    ID                  BIGINT PRIMARY KEY,
    OWNER_USER_ID       BIGINT       NOT NULL REFERENCES USERS (USER_ID),
    TYPE                VARCHAR(32)  NOT NULL,
    STATUS              VARCHAR(32)  NOT NULL,
    TITLE               VARCHAR(255),
    DESCRIPTION         TEXT,
    START_AT            TIMESTAMP,
    EXPIRES_AT          TIMESTAMP    NOT NULL,
    LOCATION_NAME       VARCHAR(255),
    LAT                 DOUBLE PRECISION,
    LON                 DOUBLE PRECISION,
    VISIBILITY_RADIUS_M INTEGER      NOT NULL DEFAULT 3000,
    CREATED_AT          TIMESTAMP    NOT NULL,
    UPDATED_AT          TIMESTAMP    NOT NULL,
    CLOSED_AT           TIMESTAMP
);

CREATE TABLE IF NOT EXISTS USER_ROLES
(
    ID      BIGINT PRIMARY KEY,
    USER_ID BIGINT      NOT NULL REFERENCES USERS (USER_ID),
    ROLE    VARCHAR(32) NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_PLANS_TYPE_STATUS_EXPIRES ON PLANS (TYPE, STATUS, EXPIRES_AT);
CREATE INDEX IF NOT EXISTS IDX_PLANS_OWNER_STATUS ON PLANS (OWNER_USER_ID, STATUS);
CREATE UNIQUE INDEX IF NOT EXISTS UX_PLANS_OWNER_ACTIVE_LIVE ON PLANS (OWNER_USER_ID)
    WHERE TYPE = 'LIVE' AND STATUS = 'ACTIVE';
CREATE INDEX IF NOT EXISTS IDX_USER_ROLES_USER ON USER_ROLES (USER_ID);

