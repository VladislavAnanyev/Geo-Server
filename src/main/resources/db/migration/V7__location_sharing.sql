CREATE TABLE LOCATION_SHARING
(
    SHARING_ID        BIGSERIAL PRIMARY KEY,
    INITIATOR_USER_ID BIGINT      NOT NULL REFERENCES USERS (USER_ID),
    TARGET_USER_ID    BIGINT      NOT NULL REFERENCES USERS (USER_ID),
    STATUS            VARCHAR(32) NOT NULL,
    CREATED_AT        TIMESTAMP   NOT NULL DEFAULT NOW(),
    ACCEPTED_AT       TIMESTAMP,
    CONSTRAINT UQ_LOCATION_SHARING_PAIR UNIQUE (INITIATOR_USER_ID, TARGET_USER_ID)
);

CREATE INDEX IDX_LOCATION_SHARING_TARGET_STATUS ON LOCATION_SHARING (TARGET_USER_ID, STATUS);
CREATE INDEX IDX_LOCATION_SHARING_INITIATOR_STATUS ON LOCATION_SHARING (INITIATOR_USER_ID, STATUS);
