CREATE TABLE CONTENT_REPORTS
(
    REPORT_ID        BIGSERIAL PRIMARY KEY,
    REPORTER_USER_ID BIGINT      NOT NULL REFERENCES USERS (USER_ID),
    TARGET_TYPE      VARCHAR(32) NOT NULL,
    TARGET_ID        BIGINT      NOT NULL,
    STATUS           VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    CREATED_AT       TIMESTAMP   NOT NULL DEFAULT NOW(),
    CONSTRAINT UQ_CONTENT_REPORT_REPORTER_TARGET
        UNIQUE (REPORTER_USER_ID, TARGET_TYPE, TARGET_ID)
);

CREATE INDEX IDX_CONTENT_REPORTS_TARGET ON CONTENT_REPORTS (TARGET_TYPE, TARGET_ID);
CREATE INDEX IDX_CONTENT_REPORTS_STATUS ON CONTENT_REPORTS (STATUS, CREATED_AT DESC);
CREATE INDEX IDX_CONTENT_REPORTS_CREATED ON CONTENT_REPORTS (CREATED_AT DESC);
