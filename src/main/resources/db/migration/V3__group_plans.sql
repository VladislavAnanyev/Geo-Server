ALTER TABLE PLANS

    ADD COLUMN MODE VARCHAR(32) NOT NULL,

    ADD COLUMN DIALOG_ID BIGINT;



CREATE INDEX IDX_PLANS_MODE_STATUS_EXPIRES ON PLANS (MODE, STATUS, EXPIRES_AT);

CREATE INDEX IDX_PLANS_DIALOG_ID ON PLANS (DIALOG_ID);



CREATE TABLE PLANS_RESPONSES

(

    ID          BIGINT PRIMARY KEY,

    PLAN_ID     BIGINT      NOT NULL REFERENCES PLANS (ID),

    USER_ID     BIGINT      NOT NULL REFERENCES USERS (USER_ID),

    STATUS      VARCHAR(32) NOT NULL,

    CREATED_AT  TIMESTAMP   NOT NULL,

    UPDATED_AT  TIMESTAMP   NOT NULL,

    DECIDED_AT  TIMESTAMP,

    CONSTRAINT UX_PLANS_RESPONSES_PLAN_USER UNIQUE (PLAN_ID, USER_ID)

);



CREATE INDEX IDX_PLANS_RESPONSES_PLAN_STATUS ON PLANS_RESPONSES (PLAN_ID, STATUS);

CREATE INDEX IDX_PLANS_RESPONSES_USER_STATUS ON PLANS_RESPONSES (USER_ID, STATUS);

