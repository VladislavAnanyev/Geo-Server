CREATE TABLE IF NOT EXISTS user_favorite_places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_user_favorite_places_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT uk_user_favorite_places_user_coords UNIQUE (user_id, lat, lng)
);

CREATE INDEX IF NOT EXISTS idx_user_favorite_places_user_id ON user_favorite_places (user_id);
