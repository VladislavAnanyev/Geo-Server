package com.example.meetings.geolocation.sharing.model.domain;

/**
 * Статусы жизненного цикла согласия на обмен геолокацией между пользователями.
 */
public enum LocationSharingStatus {
    /** Приглашение отправлено, ожидается решение получателя. */
    PENDING,
    /** Согласие подтверждено; оба видят геолокацию друг друга. */
    ACTIVE,
    /** Получатель явно отклонил приглашение. */
    REJECTED,
    /** Ранее активный обмен отозван одним из участников. */
    REVOKED
}
